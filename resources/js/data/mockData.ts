// Generate active loan mock for Budi Santoso (12,000,000 principal, 12 months, 10%)
const loan1Calc = calculateFlatLoan(12000000, 10.0, 12, '2026-01-15');
const loan1Installments = loan1Calc.schedule.map((sch, idx) => {
  const isPaid = idx < 4; // 4 installments paid
  const isOverdue = idx === 4; // current installment overdue
  const paidAmount = isPaid ? sch.totalDue : 0;
  return {
    id: `inst-1-${sch.sequenceNo}`,
    loanId: 'loan-1',
    sequenceNo: sch.sequenceNo,
    dueDate: sch.dueDate,
    principalDue: sch.principalDue,
    interestDue: sch.interestDue,
    lateFeeDue: isOverdue ? 15000 : 0,
    totalDue: sch.totalDue + (isOverdue ? 15000 : 0),
    paidAmount,
    remainingAmount: (sch.totalDue + (isOverdue ? 15000 : 0)) - paidAmount,
    status: (isPaid ? 'paid' : isOverdue ? 'overdue' : 'unpaid') as any,
    paidAt: isPaid ? `2026-0${idx + 2}-12T10:00:00Z` : undefined,
  };
});

const paidTotalLoan1 = loan1Installments.filter(i => i.status === 'paid').reduce((acc, i) => acc + i.totalDue, 0);

